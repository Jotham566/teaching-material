def check_guard(task_code, check_code):
    """Two lines for the top of a student check cell: if the student has not yet made the variables the check needs, say so plainly
    instead of showing a NameError traceback."""
    import builtins
    try: t, c = ast.parse(task_code), ast.parse(check_code)
    except SyntaxError: return ''
    made = {x.id for x in ast.walk(t) if isinstance(x, ast.Name) and isinstance(x.ctx, ast.Store)}
    own = {x.id for x in ast.walk(c) if isinstance(x, ast.Name) and isinstance(x.ctx, ast.Store)}
    used = []
    for x in ast.walk(c):
        if isinstance(x, ast.Name) and isinstance(x.ctx, ast.Load) and x.id in made and x.id not in own and not hasattr(builtins, x.id) and x.id not in used: used.append(x.id)
    if not used: return ''
    names = ', '.join(repr(u) for u in sorted(used))
    return (f"_missing = [v for v in ({names},) if v not in globals()]\n"
            "assert not _missing, f'Not set yet: {_missing}. Finish the Your turn cell above, run it, then run this cell again.'\n")

def make_notebook(n, content, solution):
    sess = cur.SESSIONS[n]; cells = []
    def md(t): cells.append({'cell_type': 'markdown', 'metadata': {}, 'source': t.splitlines(True)})
    def code(t): cells.append({'cell_type': 'code', 'metadata': {}, 'execution_count': None, 'outputs': [], 'source': t.splitlines(True)})
    lab = content.get('lab', {})
    md(f"# Session {n:02d}: {sess['title']}\n\n{lab.get('intro', sess['lab'])}\n\n**{'SOLUTION VERSION. Tutor only.' if solution else 'Student version.'}** Run the cells from the top. Each cell that starts with '# Your turn' is yours to complete. Run it, then run the check cell after it: the check tells you if you are right and what to fix.")
    code(SETUP)
    prev = ''                                     # the solutions of the task cells so far, to find the names a check cell needs
    for c in lab.get('cells', []):
        if 'md' in c: md(c['md'])
        elif 'code' in c:
            if 'starter' in c: prev += '\n' + c['code']
            src = c['code'] if (solution or 'starter' not in c) else c['starter']
            if not solution and 'starter' not in c and prev: src = check_guard(prev, c['code']) + src
            code(src)
    return {'cells': cells, 'metadata': {'colab': {'name': f"{n:02d}_{'solution' if solution else 'student'}.ipynb", 'provenance': []}, 'kernelspec': {'display_name': 'Python 3', 'name': 'python3'}, 'language_info': {'name': 'python'}}, 'nbformat': 4, 'nbformat_minor': 5}

def build(n):
    rc, deck = check(n)
    if rc: print('Not written: fix the HARD problems first.'); return rc
    content = load(n); SLIDES.mkdir(parents=True, exist_ok=True); NB_STUDENT.mkdir(parents=True, exist_ok=True); NB_SOLUTION.mkdir(parents=True, exist_ok=True)
    deck.save(SLIDES / f'{title_file(n)}.pptx')
    if content.get('lab', {}).get('cells'):
        (NB_STUDENT / f'{title_file(n)} (student).ipynb').write_text(json.dumps(make_notebook(n, content, False), indent=1, ensure_ascii=False), encoding='utf-8')
        (NB_SOLUTION / f'{title_file(n)} (solution).ipynb').write_text(json.dumps(make_notebook(n, content, True), indent=1, ensure_ascii=False), encoding='utf-8')
    print('written', title_file(n)); return 0

def make_sheets_file():
    """A workbook small enough for Google Sheets: 2,000 sampled orders with their lines, and the small tables."""
    import pandas as pd
    from openpyxl import Workbook
    od = pd.read_csv(DATA / 'orders.csv'); ol = pd.read_csv(DATA / 'order_lines.csv'); samp = od.sample(2000, random_state=7).sort_values('order_id'); lines = ol[ol.order_id.isin(samp.order_id)]
    with pd.ExcelWriter(DATA / 'lakeside_for_sheets.xlsx', engine='openpyxl') as w:
        samp.to_excel(w, 'orders', index=False); lines.to_excel(w, 'order_lines', index=False)
        for k in ('branches', 'products', 'customers'): pd.read_csv(DATA / f'{k}.csv').to_excel(w, k, index=False)
        pd.read_csv(DATA / 'branch_weeks.csv').to_excel(w, 'branch_weeks', index=False)
        pd.DataFrame({'note': ['This workbook holds a 2,000-order sample of orders.csv with its order lines, so it opens quickly in Google Sheets.', 'Answers from the full CSV files in Python will differ slightly from answers here. That difference is the point of Session 4.']}).to_excel(w, 'READ ME', index=False)

def make_data():
    DATA.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, str(HERE / 'build_teaching_data.py'), str(DATA)], check=True, stdout=subprocess.DEVNULL)
    subprocess.run([sys.executable, str(HERE / 'figs.py'), str(DATA), str(FIGS)], check=True)
    db = DATA / 'lakeside.db'
    if db.exists(): db.unlink()
    import pandas as pd
    con = sqlite3.connect(':memory:')
    for t in ('branches', 'products', 'customers', 'orders', 'order_lines', 'returns', 'branch_weeks', 'offer_test', 'feedback'): pd.read_csv(DATA / f'{t}.csv').to_sql(t, con, index=False)
    disk = sqlite3.connect(str(db)); con.backup(disk); disk.close(); con.close()
    make_sheets_file()
    zp = DATA.parent / 'data.zip'
    with zipfile.ZipFile(zp, 'w', zipfile.ZIP_DEFLATED) as z:
        for f in sorted(DATA.rglob('*')):
            if f.is_file(): z.write(f, f.relative_to(DATA))
    print('data, figures, lakeside.db and data.zip ready')

