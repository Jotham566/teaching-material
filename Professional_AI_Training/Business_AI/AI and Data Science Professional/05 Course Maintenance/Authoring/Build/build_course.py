def collect_code(content):
    blocks = []
    for i, s in enumerate(content['slides'], 1):
        if s['type'] == 'code': blocks.append(dict(label=f'slide {i} "{s["title"][:40]}"', code=s['code'], lang=s.get('lang', 'python'), output=s.get('output'), expect_error=s.get('expect_error', False)))
    return blocks

def notebook_cells(content): return content.get('lab', {}).get('cells', [])

def check(n, quiet=False):
    probs = []; sess = dict(cur.SESSIONS[n]); sess['shape'] = cur.SESSION_SHAPE
    try: content = load(n)
    except SystemExit as e: print(e); return 1, None
    deck = build_deck(n, content, probs)
    # code blocks on slides
    for r in run_blocks(collect_code(content), probs, f'S{n}'): pass
    # notebook solution cells
    nb_blocks = []
    for j, c in enumerate(notebook_cells(content), 1):
        if 'code' in c: nb_blocks.append(dict(label=f'notebook cell {j}', code=c['code'], lang='python', output=None, expect_error=c.get('expect_error', False)))
    if nb_blocks:
        res = run_blocks(nb_blocks, probs, f'S{n}')
        ran = sum(1 for r in res if r[0] in ('ran', 'failed as intended')); skip = sum(1 for r in res if r[0].startswith('syntax') or r[0].startswith('depends'))
        if not quiet: print(f'  notebook: {ran} cells executed, {skip} syntax-checked only (library not available here)')
    # structural requirements
    sl = content['slides']; kinds = [s['type'] for s in sl]
    if 'trap' not in kinds: probs.append(('HARD', 'structure', 'needs one trap slide'))
    if 'check' not in kinds: probs.append(('HARD', 'structure', 'needs an exit check slide (type check)'))
    if 'steps' not in kinds: probs.append(('HARD', 'structure', 'needs a lab slide (type steps)'))
    if kinds[-1] != 'summary': probs.append(('HARD', 'structure', 'the last slide must be type summary'))
    if kinds[0] != 'check': probs.append(('HARD', 'structure', 'the first content slide must be a recall or warm-up check (type check)'))
    if deck and deck.animated < 5: probs.append(('HARD', 'structure', f'only {deck.animated} animated slides; use flow, cycle, compare, code with says, check, trap, figure with look or matrix reveals (at least 5)'))
    if sess['code'] and kinds.count('code') < 3: probs.append(('HARD', 'structure', 'a coding session needs at least 3 code slides'))
    if not (14 <= len(sl) <= 22): probs.append(('HARD', 'structure', f'{len(sl)} content slides; aim for 15 to 20'))
    if not sum(1 for k in kinds if k in ('figure',)) and not any(isinstance(s.get('fig'), (str, dict)) for s in sl): probs.append(('HARD', 'structure', 'use at least one figure from the catalog'))
    if not content.get('lab', {}).get('cells') and sess['code']: probs.append(('HARD', 'structure', 'a coding session needs lab notebook cells'))
    if not sess['code'] and not content.get('lab', {}).get('sheet_tasks'): probs.append(('HARD', 'structure', 'a no-code session needs lab.sheet_tasks (a list of Sheets tasks with the expected answers)'))
    v = content.get('vocab', [])
    if not 4 <= len(v) <= 8: probs.append(('HARD', 'vocab', f'{len(v)} vocabulary terms (need 4 to 8)'))
    # notes for auto slides
    for k in ('notes_title', 'notes_outcomes', 'notes_words'): lint_note(content.get(k, ''), 0, k, probs)
    PAUSES = ["Take your time.", "Have a think.", "No rush.", "Think it over.", "Give that a moment.", "Sit with it for a second.", "Give that a little thought.", "See what you come up with.", "Say it out loud if it helps.", "Let's hear your answer first.", "Work it through before I answer.", "Take a moment with that."]
    allnotes = [content.get(k, '') for k in ('notes_title', 'notes_outcomes', 'notes_words')] + [s.get('notes', '') for s in sl]
    for ph in PAUSES:
        cnt = sum(x.count(ph) for x in allnotes)
        if cnt > 1: probs.append(('WARN', 'notes', f'pause line {ph!r} used {cnt} times in this session: vary it'))
    hard = [p for p in probs if p[0] == 'HARD']; warn = [p for p in probs if p[0] == 'WARN']
    if not quiet:
        for sev, where, msg in probs: print(f'{sev:5} {where}: {msg}')
        print(f'Session {n}: {len(sl)} content slides, {deck.n if deck else 0} slides built, {deck.clicks if deck else 0} clicks on {deck.animated if deck else 0} animated slides. HARD problems: {len(hard)}. Warnings: {len(warn)}.')
    return (1 if hard else 0), deck

def build_deck(n, content, probs):
    sess = dict(cur.SESSIONS[n]); sess['shape'] = cur.SESSION_SHAPE
    for k in ('notes_title', 'notes_outcomes', 'notes_words'): sess[k] = content.get(k, '')
    hero = FIGS / f"hero_{sess['module']}.png"
    deck = dk.Deck(sess, vocab=[tuple(x) for x in content.get('vocab', [])], fig_dir=FIGS, hero=hero)
    try:
        deck.title_slide(); deck.outcomes_slide(); deck.words_slide()
        for i, s in enumerate(content['slides'], 1):
            before = deck.clicks
            try: deck.add(s)
            except dk.FitError as e: probs.append(('HARD', f'slide {i} "{s.get("title", s["type"])[:40]}"', f'does not fit: {e}')); continue
            except Exception as e: probs.append(('HARD', f'slide {i} "{s.get("title", s["type"])[:40]}"', f'{type(e).__name__}: {e}')); continue
            clicks = deck.clicks - before
            lint_note(s.get('notes', ''), clicks, f'slide {i} notes', probs)
            s['_clicks'] = clicks
    except Exception as e:
        probs.append(('HARD', 'build', f'{type(e).__name__}: {e}')); traceback.print_exc()
    return deck

