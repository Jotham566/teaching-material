# ------------------------------------------------------------------ notes lint (read-aloud scripts)
HARD = [(r'\bclicks?\b', 'mentions a click'), (r'\bthis slide\b|\bnext slide\b|\bprevious slide\b|\bon the screen\b', 'talks about the slide as an object'),
        (r'\bI ask\b|\bsatisfactory answer\b|\bgood answer\b|\bfollow-up if needed\b', 'facilitator-guide phrasing'), (r'https?://|www\.|Sources?:|Playback:', 'link or Sources line'),
        (r'[\[\]{}<>]', 'brackets or markup'), (r'—|–', 'dash aside'), (r'\b(genuinely|honestly|straightforward|delve|pivotal|robust|leverage|crucial)\b', 'banned word'),
        (r'\b(she|her|hers|he|his)\b', 'gendered learner'), (r'^[A-Z][A-Za-z ]{1,28}:\s', 'label at paragraph start'), (r'\bthe learner\b|\bfacilitator\b|\bpresenter\b', 'third-person guide wording'),
        (r'\*\*|^#|^- |^\d+\.\s', 'markdown or list')]
WARN = [(r'\bnot\b[^.?!]{0,70}\bbut\b', 'possible X-not-Y'), (r',\s*not\b', 'possible X-not-Y'), (r'\bnot just\b|\bnot only\b', 'possible X-not-Y'), (r'\brather than\b', 'possible contrast')]
STOCK = ['Take a moment with that.', 'Give that a little thought.', "Here's a question for you."]

def lint_note(note, clicks, label, probs):
    paras = [p for p in note.split('\n\n') if p.strip()]; w = len(note.split())
    if clicks and len(paras) < clicks + 1: probs.append(('HARD', label, f'{len(paras)} paragraphs but the slide has {clicks} clicks: write an opening paragraph plus one per click'))
    if not 40 <= w <= 300: probs.append(('HARD', label, f'note has {w} words (allowed 40 to 300)'))
    for pat, why in HARD:
        m = re.search(pat, note, re.I | re.M)
        if m: probs.append(('HARD', label, f'{why}: ...{note[max(0, m.start()-25):m.end()+25]!r}'.replace('\n', ' ')))
    for pat, why in WARN:
        m = re.search(pat, note, re.I | re.M)
        if m: probs.append(('WARN', label, f'{why}: ...{note[max(0, m.start()-25):m.end()+25]!r}'.replace('\n', ' ')))
    for s in STOCK:
        if s in note: probs.append(('WARN', label, f'stock phrase {s!r}: vary the wording'))

# ------------------------------------------------------------------ code execution (pandas, numpy, matplotlib, sqlite only)
class Timeout(Exception): pass
def _alarm(sig, frm): raise Timeout()

def run_blocks(blocks, probs, label_prefix):
    """blocks: list of dict(label, code, lang, output, expect_error). Executed in order in ONE namespace with cwd = data folder."""
    import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
    ns = {'__name__': '__main__'}; cwd = os.getcwd(); skipped_names = set(); results = []
    os.chdir(DATA)
    try:
        for b in blocks:
            lab = f"{label_prefix} {b['label']}"; code = b['code']
            if b['lang'] == 'sql':
                try:
                    con = sqlite3.connect(f'file:{DATA / "lakeside.db"}?mode=ro', uri=True); cur_ = con.execute(code.strip().rstrip(';')); rows = cur_.fetchall(); cols = [d[0] for d in cur_.description]; con.close()
                    actual = (' '.join(str(x) for x in cols) + '\n' + '\n'.join(' '.join(str(x) for x in r) for r in rows[:30])) if rows else ' '.join(cols)
                    results.append(('SQL ok', lab, len(rows)))
                    _compare(b, actual, probs, lab)
                except Exception as e: probs.append(('HARD', lab, f'SQL failed: {e}'))
                continue
            try: ast.parse(code)
            except SyntaxError as e: probs.append(('HARD', lab, f'syntax error line {e.lineno}: {e.msg}')); continue
            if HEAVY.search(code):
                results.append(('syntax ok; not executed (needs a library this machine lacks)', lab, 0))
                # remember names defined here so later NameErrors are explained, not failed
                for mm in re.finditer(r'^\s*([A-Za-z_][A-Za-z_0-9]*)\s*=', code, re.M): skipped_names.add(mm.group(1))
                continue
            buf = io.StringIO()
            signal.signal(signal.SIGALRM, _alarm); signal.alarm(90)
            try:
                with contextlib.redirect_stdout(buf):
                    tree = ast.parse(code); last = None
                    if tree.body and isinstance(tree.body[-1], ast.Expr): last = ast.Expression(tree.body.pop().value)
                    exec(compile(tree, lab, 'exec'), ns)
                    if last is not None:
                        val = eval(compile(last, lab, 'eval'), ns)
                        if val is not None: print(val if not hasattr(val, 'to_string') else val.to_string())
                signal.alarm(0)
                if b.get('expect_error'): probs.append(('HARD', lab, 'this block is marked expect_error but ran without an error'))
                else: _compare(b, buf.getvalue(), probs, lab); results.append(('ran', lab, 0))
            except Timeout: probs.append(('HARD', lab, 'timed out after 90 s'))
            except BaseException as e:
                signal.alarm(0)
                if b.get('expect_error'):
                    results.append(('failed as intended', lab, 0)); _compare(b, buf.getvalue() + '\n' + f'{type(e).__name__}: {e}', probs, lab)
                elif isinstance(e, NameError) and any(n in str(e) for n in skipped_names): results.append(('depends on a block not executed here', lab, 0))
                else: probs.append(('HARD', lab, f'{type(e).__name__}: {e}'))
            finally: plt.close('all')
    finally: os.chdir(cwd)
    return results

def _norm(s): return re.sub(r'\s+', ' ', s).strip()
def _compare(b, actual, probs, lab):
    out = b.get('output')
    if not out: return
    na = _norm(actual)
    for line in out.strip().split('\n'):
        l = _norm(line)
        if not l or l in ('...', '…') or set(l) <= set('-=| '): continue
        if l not in na:
            probs.append(('HARD', lab, f'slide output line {l!r} is not in the real output. Real output starts: {na[:160]!r}')); return

