def nb(*cells):
    return json.dumps({'cells': [{'cell_type': 'code', 'metadata': {}, 'source': c} for c in cells]})


def total(record):
    return sum(q['awarded'] for q in record['questions'].values())


class HostHelpers(unittest.TestCase):
    """Pure helpers: no Docker."""

    def test_alias_resolver_maps_colab_renames_and_paths(self):
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / 'campus_energy.csv').write_text('a\n1\n')
            want = Path(d) / 'campus_energy.csv'
            for path in ('campus_energy (1).csv', 'campus_energy(2).csv', 'campus_energy[1].csv',
                         '/content/campus_energy (1).csv', '/content/sample_data/campus_energy.csv',
                         'sample_data/campus_energy.csv', '/content/drive/MyDrive/W05/campus_energy.csv',
                         '/campus_energy.csv', 'Copy of campus_energy.csv', 'CAMPUS_ENERGY.CSV'):
                self.assertEqual(colab_shim.resolve_data_path(path, [d]), want, path)
            for path in ('other.csv', 'campus_energy_v2.csv', 'campus_energy.txt', 'https://x/campus_energy.csv'):
                self.assertIsNone(colab_shim.resolve_data_path(path, [d]), path)
            # An existing path is never redirected.
            self.assertIsNone(colab_shim.resolve_data_path(str(want), [d]))

    def test_ipython_dedent(self):
        self.assertEqual(colab_shim.ipython_cell_source(' x = 1\n y = 2\n'), 'x = 1\ny = 2\n')
        self.assertEqual(colab_shim.ipython_cell_source('\n\n  def f():\n      return 1\n'), 'def f():\n    return 1\n')
        code, dedented = colab_shim.compile_cell('x = 1\n', 'c')
        self.assertFalse(dedented)
        code, dedented = colab_shim.compile_cell(' x = 1\n', 'c')
        self.assertTrue(dedented)
        with self.assertRaises(SyntaxError):
            colab_shim.compile_cell('x = (\n', 'c')

    def test_plt_close_after_cell(self):
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        plt.figure(); plt.plot([1, 2])
        self.assertTrue(plt.get_fignums())
        colab_shim.after_cell()
        self.assertFalse(plt.get_fignums())

    def test_colab_py_export_becomes_cells(self):
        text = '# -*- coding: utf-8 -*-\n"""W05.ipynb\n\nAutomatically generated by Colab."""\n\n!pip install x\nimport math\n\n"""## Task"""\n\nx = 1\ndef f(a):\n    return a\n'
        nbk = colab_shim.colab_py_to_notebook(text)
        sources = [c['source'] for c in nbk['cells']]
        self.assertEqual(sources, ['# !pip install x\nimport math', 'x = 1', 'def f(a):\n    return a'])

    def test_code_spans_from_document_text(self):
        text = 'My report\nResults: 297\nSource\nimport csv\nvalid_count = 0\nfor r in []:\n    valid_count += 1\nThanks'
        self.assertEqual(colab_shim.code_spans(text), ['import csv\nvalid_count = 0\nfor r in []:\n    valid_count += 1'])

    def test_alias_tiers(self):
        self.assertEqual(gf.alias_tier('n_meters', 'n_meter'), 'spelling')
        self.assertEqual(gf.alias_tier('cost_per_kwh', 'cosr_per_kwh'), 'spelling')
        self.assertEqual(gf.alias_tier('weight_n', 'Weight_N'), 'spelling')
