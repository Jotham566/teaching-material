class IntakeTests(unittest.TestCase):
    """grade_ca_batch.prepare_submission: no Docker."""

    def setUp(self):
        import grade_ca_batch
        self.gcb = grade_ca_batch
        self.tmp = tempfile.TemporaryDirectory()
        self.src = Path(self.tmp.name)
        (self.src / 'files').mkdir()

    def tearDown(self):
        self.tmp.cleanup()

    def upload(self, name, data):
        fid = hashlib.sha256(name.encode()).hexdigest()[:12]
        export = fid + Path(name).suffix.lower()
        (self.src / 'files' / export).write_bytes(data)
        return {fid: dict(id=fid, original_name=name, export_name=export, sha256=hashlib.sha256(data).hexdigest(), size=len(data))}

    def prep(self, files, assessment='W05'):
        r = dict(file_ids=list(files), assessment=assessment, student_id='99/TEST/000/DEMO-X')
        return self.gcb.prepare_submission(r, files, self.src, self.src / 'cache')

    def test_zip_notebook_is_expanded(self):
        buf = self.src / 'tmp.zip'
        with zipfile.ZipFile(buf, 'w') as z:
            z.writestr('repo-main/A2_Proof_of_Life.ipynb', nb('readings = 17'))
            z.writestr('repo-main/README.md', '# readme')
        p = self.prep(self.upload('repo-main - Student.zip', buf.read_bytes()), 'W02')
        self.assertEqual(p['status'], 'NOTEBOOK')
        self.assertIn('readings = 17', p['notebook_text'])
        self.assertIn('ZIP', p['origin_note'])

    def test_colab_py_export_is_converted(self):
        p = self.prep(self.upload('w05_student - X.py', b'# -*- coding: utf-8 -*-\n"""Colab"""\nn_meters = 8\n'))
        self.assertEqual(p['status'], 'NOTEBOOK')
        self.assertEqual(json.loads(p['notebook_text'])['cells'][0]['source'], 'n_meters = 8')

    def docx(self, text):
        body = ''.join('<w:p><w:r><w:t xml:space="preserve">%s</w:t></w:r></w:p>' % line.replace('&', '&amp;').replace('<', '&lt;') for line in text.split('\n'))
        buf = self.src / 'tmp.docx'
        with zipfile.ZipFile(buf, 'w') as z:
            z.writestr('word/document.xml', '<w:document xmlns:w="w"><w:body>%s</w:body></w:document>' % body)
        return buf.read_bytes()

    def test_docx_with_notebook_json_or_pasted_code_is_converted(self):
        p = self.prep(self.upload('A5.docx', self.docx(nb('n_meters = 8'))))
        self.assertEqual(json.loads(p['notebook_text'])['cells'][0]['source'], 'n_meters = 8')
        p = self.prep(self.upload('A4.docx', self.docx('Report\nimport csv\nvalid_count = 3\nabove_limit = 1\nEnd of report')), 'W04')
        self.assertEqual(p['status'], 'NOTEBOOK')
        self.assertIn('valid_count = 3', p['notebook_text'])

    def test_zero_byte_and_unreadable_uploads_cannot_be_judged(self):
        p = self.prep(self.upload('W05_student (2).ipynb', b''))
        self.assertEqual((p['status'], p['reason_code']), ('CANNOT_JUDGE', 'EMPTY'))
        p = self.prep(self.upload('W03.pdf', b'%PDF-1.4 not a notebook'))
        self.assertEqual((p['status'], p['reason_code']), ('CANNOT_JUDGE', 'UNREADABLE'))
        p = self.prep(self.upload('bad.ipynb', b'not json'))
        self.assertEqual(p['status'], 'CANNOT_JUDGE')

    def test_direct_notebook_unchanged(self):
        text = nb('n_meters = 8')
        p = self.prep(self.upload('24_1_X_W05.ipynb', text.encode()))
        self.assertEqual((p['status'], p['notebook_text'], p['origin_note']), ('NOTEBOOK', text, ''))


class SandboxTests(unittest.TestCase):
    """Runs synthetic notebooks in the Docker sandbox."""

    @classmethod
    def setUpClass(cls):
        from isolated_grading import preflight
        preflight()

    def grade(self, text, assignment, data=None, cohort='CML3111', name='S99997'):
        from batch_grade import grade_one
        with tempfile.TemporaryDirectory() as tmp:
            p = Path(tmp) / ('%s_%s.ipynb' % (name, assignment))
            p.write_text(text)
            return grade_one(str(p), str(HERE / ('specs/spec_%s.py' % assignment)),
                             str(HERE / ('specs/hidden/spec_%s_hidden.py' % assignment)),
                             assignment, cohort, str(data) if data else None, 5, 60, None)

    def test_renamed_and_relocated_csv_is_found(self):
        for path in ('campus_energy (1).csv', 'campus_energy[1].csv', '/content/sample_data/campus_energy.csv',
                     '/content/drive/MyDrive/campus_energy.csv', '/campus_energy.csv'):
            r = self.grade(nb('import pandas as pd\ndf = pd.read_csv(%r)' % path, W05_ANSWERS), 'W05', W05_DATA)
            self.assertEqual(total(r), 20, (path, r))
            self.assertFalse(r['cell_errors'], r)
        r = self.grade(nb('import csv\nwith open("/content/sample_data/motor_test_bench (1).csv") as f:rows=list(csv.DictReader(f))\nvalid_count=len([r for r in rows if r["winding_temp_c"]!=""])'), 'W04', W04_DATA)
        self.assertEqual(r['questions']['q1']['awarded'], 5, r)

    def test_display_ipython_drive_and_dedent(self):
        r = self.grade(nb('from google.colab import drive\ndrive.mount("/content/drive")',
                          'from IPython.display import display, HTML\ndisplay(HTML("<b>x</b>"))',
                          'import pandas as pd\ndf = pd.read_csv("campus_energy.csv")\ndisplay(df.head())',
                          ' n_meters = df["meter_id"].nunique()\n print(n_meters)',
                          W05_ANSWERS.split('\n', 1)[1]), 'W05', W05_DATA)
        self.assertFalse(r['cell_errors'], r)
        self.assertEqual(total(r), 20, r)

    def test_figures_are_closed_after_each_cell(self):
        r = self.grade(nb('import matplotlib.pyplot as plt\nplt.plot([1,2,3])',
                          'weight_n = 40*9.81 if not plt.get_fignums() else 0'), 'W03')
        self.assertEqual(r['questions']['q1']['awarded'], 3, r)

    def test_own_cell_check_survives_a_later_rebind(self):
        r = self.grade(nb(W03_FULL, 'percent_error = [abs(r-100) for r in [98.5, 111.4]]'), 'W03')
        self.assertEqual(r['questions']['q2']['awarded'], 4, r)
        self.assertEqual(total(r), 20, r)
        self.assertEqual(r['fairness']['notes']['q2']['fix'], 'own-cell check')

    def test_aliases_spelling_full_and_renamed_half(self):
        r = self.grade(nb('import pandas as pd\ndf = pd.read_csv("campus_energy.csv")',
                          'n_meter = df["meter_id"].nunique()\ndf["cost_per_kw"] = df["cost_ugx"] / df["kwh"]',
                          'high_use = df[df["kwh"] > 5000]\nmean_cost_per_kwh = df["cost_per_kw"].mean()\npeak_building = df.groupby("building")["kwh"].sum().idxmax()'),
                       'W05', W05_DATA)
        self.assertEqual(r['questions']['q2']['awarded'], 3, r)  # n_meter: spelling, accepted
        self.assertEqual(r['questions']['q3']['awarded'], 4, r)  # column cost_per_kw: spelling
        self.assertEqual(r['questions']['q4']['awarded'], 4, r)
        r = self.grade(nb(W03_FULL.replace('weight_n=', 'weight=').replace('worst_reading=', 'worst=')), 'W03')
        self.assertEqual(r['questions']['q1']['awarded'], 1.5, r)   # half of 3
        self.assertEqual(r['questions']['q5']['awarded'], 3.75, r)  # 2.5 earned + half of the other 2.5

    def test_full_marks_and_wrong_answers_unchanged(self):
        r = self.grade(nb(W03_FULL), 'W03')
        self.assertEqual(total(r), 20, r)
        self.assertFalse(r['fairness']['notes'])
        r = self.grade(nb('weight_n = 40\ndef percent_error(m, e):return 0'), 'W03')
        self.assertEqual(total(r), 0, r)

    def test_other_assessments_keep_original_sandbox(self):
        from isolated_grading import evaluate  # noqa: F401
        r = self.grade(nb('display(1)', 'weight_n = 40*9.81'), 'W03')
        self.assertFalse(r['cell_errors'], r)
        # With fairness switched off the original behaviour returns (display is undefined).
        import batch_grade
        import isolated_grading
        original = isolated_grading.evaluate
        try:
            isolated_grading.evaluate = lambda *a: original(*a, fairness=False)
            r = self.grade(nb('display(1)', 'weight_n = 40*9.81'), 'W03')
        finally:
            isolated_grading.evaluate = original
        self.assertEqual(r['cell_errors'][0]['etype'], 'NameError', r)
        self.assertNotIn('fairness', r)
        self.assertTrue(batch_grade)


