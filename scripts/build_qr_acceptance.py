# -*- coding: utf-8 -*-
"""The QR acceptance card: three codes plus the text each must decode to.

Print or project this and scan it with a phone. It is the only test that
proves the codes work on the hardware they will actually be used on.

Regenerated 2026-09-09 after a real bug: the format information was being
written in reverse bit order, so every code produced before that fix was
structurally perfect, passed a round trip through this project's own
decoder, and scanned as nothing at all. Nothing about that failure was
visible without an external decoder or a phone.
"""
import os
import sys

import os as _os
_HERE = _os.path.dirname(_os.path.abspath(__file__))
_ROOT = _os.path.dirname(_HERE)
sys.path.insert(0, _HERE)

from PIL import Image, ImageDraw, ImageFont

import qrgen

OUT = _ROOT + "/IUEA_Teaching_Plan/QR_encoder_acceptance_test.png"

CASES = [
    ("https://example.com", "Plain short URL"),
    ("https://iuea.ac.ug", "The university site"),
    ("CML3112 Week 1 quiz - if you can read this, the encoder works",
     "A longer string, denser grid"),
]

W, H = 1500, 760
img = Image.new("RGB", (W, H), "white")
d = ImageDraw.Draw(img)


def font(sz, bold=False):
    for p in ("/usr/share/fonts/truetype/dejavu/DejaVuSans%s.ttf"
              % ("-Bold" if bold else ""),):
        if os.path.exists(p):
            return ImageFont.truetype(p, sz)
    return ImageFont.load_default()


d.text((40, 34), "QR encoder acceptance test", fill="#1C3144", font=font(40, True))
d.text((40, 90),
       "Scan each code with your phone. It must decode to exactly the text "
       "printed beneath it.",
       fill="#444", font=font(20))
d.text((40, 118),
       "If any code does not scan, stop and say so: the quiz QR codes in the "
       "decks come from this same encoder.",
       fill="#444", font=font(20))

x = 40
for text, label in CASES:
    tmp = "/tmp/_acc_%d.png" % abs(hash(text))
    qrgen.png(text, tmp, ec="Q", module_px=10, quiet=8)
    qr = Image.open(tmp)
    qr = qr.resize((380, 380), Image.NEAREST)
    img.paste(qr, (x, 180))
    d.text((x, 578), label, fill="#1C3144", font=font(19, True))
    # wrap the expected text
    words, line, y = text.split(), "", 606
    for w in words:
        trial = (line + " " + w).strip()
        if d.textlength(trial, font=font(15)) > 360:
            d.text((x, y), line, fill="#666", font=font(15))
            y += 21
            line = w
        else:
            line = trial
    d.text((x, y), line, fill="#666", font=font(15))
    x += 470

d.text((40, H - 40),
       "Generated by qrgen.py, verified against OpenCV's decoder. "
       "Level Q error correction, 8-module quiet zone.",
       fill="#888", font=font(15))

img.save(OUT)
print("saved", OUT)

# Prove it before shipping it: decode the finished card itself.
try:
    import cv2
    import numpy as np
    det = cv2.QRCodeDetector()
    gray = cv2.cvtColor(np.array(img), cv2.COLOR_RGB2GRAY)
    retval, decoded, _, _ = det.detectAndDecodeMulti(gray)
    found = set(t for t in (decoded or []) if t)
    want = set(t for t, _ in CASES)
    missing = want - found
    print("  codes on the card that OpenCV read back: %d of %d"
          % (len(want) - len(missing), len(want)))
    if missing:
        print("  NOT READ:", missing)
        sys.exit(1)
    print("  every code on the card decodes to its printed text")
except ImportError:
    print("  (OpenCV not available here, card not self-verified)")
