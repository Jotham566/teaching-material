def rewrite_links(links):
    md = BASE / "Assignment_Submission_Links.md"; backup(md); text = md.read_text(); total = 0
    for (code, label), (opens, close) in links.items():
        pat = re.compile(rf"(?m)^(\| {label}: [^|]*\| )([^|]*)( \| )([^|]*)( \| \[Submit\]\([^)]*\) \|)$")
        sec = text.index(f"## {code}"); nxt = text.find("\n## ", sec + 1); nxt = len(text) if nxt < 0 else nxt
        seg = text[sec:nxt]; new, n = pat.subn(lambda m: m.group(1) + m.group(2) + m.group(3) + close + m.group(5), seg, count=1)
        assert n == 1, (code, label, n)
        total += n; text = text[:sec] + new + text[nxt:]
    old_note = re.search(r"(?m)^\*\*From Week 8 the weekly assignment and quiz become block assessments.*$", text)
    assert old_note, "block note line not found"
    new_note = ("**From Week 8 the weekly assignment and quiz become block assessments (arrangement of 2 November 2026).** "
                "A7 and A8 form Block 1 and close together; A9, A10 and A11 form Block 2 and close together. The closing times in the tables below are the block deadlines. "
                "The semester ends at Week 12 and there is no Practical Test 2. The arrangement is in [Block_Assessment_Arrangement_2026-11-02.md](Block_Assessment_Arrangement_2026-11-02.md) "
                "(the 30 October note is superseded).")
    text = text[:old_note.start()] + new_note + text[old_note.end():]
    # Practical Test 2 is retired; the project and demo submission windows are not defined yet.
    for rid, label_re, replacement in (
        ("TEST2", r"TEST2: Practical Test 2", "RETIRED on 2 November 2026 (no Practical Test 2)"),
        ("ML_PROJECT", r"ML_PROJECT: Engineering ML project", "to be confirmed by the lecturer"),
        ("DEMO", r"DEMO: Presentation and individual reflection", "to be confirmed by the lecturer (demo day is in Week 12)")):
        pat = re.compile(rf"(?m)^(\| {label_re} \| )([^|]*)( \| )([^|]*)( \| )(\[Submit\]\([^)]*\)) \|$")
        def sub(m, replacement=replacement, rid=rid):
            if rid == "TEST2": return m.group(1) + replacement + m.group(3) + replacement + m.group(5) + "retired |"
            return m.group(1) + replacement + m.group(3) + replacement + m.group(5) + m.group(6) + " |"
        done = 0
        if rid == "TEST2" or True:
            # skip rows already rewritten: they no longer carry a timestamp in the second column
            def guarded(m):
                if not re.match(r"\d{4}-\d\d-\d\dT", m.group(2)): return m.group(0)
                return sub(m)
            text, n = pat.subn(guarded, text)
        already = len(re.findall(rf"(?m)^\| {label_re} \| (?:RETIRED|to be confirmed)", text))
        assert already == 3, (rid, n, already)
    md.write_text(text); return total


