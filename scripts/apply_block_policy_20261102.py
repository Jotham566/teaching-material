def ascii_only(text, name):
    bad = sorted({c for c in text if ord(c) > 127})
    if bad: raise SystemExit(f"{name}: non-ASCII characters {bad[:8]}; generated .gs must be pure ASCII")
    return text


def block_of_part():
    return {p["id"]: (b, p) for b in POL["blocks"] for p in b["assignment_parts"]}


def update_registry():
    path = ROOT / "data" / "assessments.json"; backup(path); rows = json.loads(path.read_text()); calls = []; links = {}
    parts = block_of_part()
    for pid, (b, p) in parts.items():
        n = len(b["assignment_parts"])
        for code in COHORTS:
            hits = [x for x in rows if x["key"] == f"{code}|{pid}"]
            assert len(hits) == 1, (code, pid, len(hits))
            r = hits[0]; close = b["assignment_closes"][code]
            assert r["label"] == p["label"] and r["title"] == p["title"], (r["label"], p["label"])
            r["closes_at"] = close; r["block"] = b["id"]; r["block_part"] = p["part"]
            r["delivery_note"] = f"{b['label']} assignment, part {p['part']} of {n}. All parts of the block close together."
            calls.append((r["key"], r["opens_at"], close)); links[(code, p["label"])] = (r["opens_at"], close)
    retire_rows(rows)
    path.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n")
    return calls, links


def retire_rows(rows):
    """Practical Test 2 is dropped; the project and demo dates are not defined yet. Follow the A6 pattern: keep the original
    dates under original_*, blank the live ones so no form can open, and say why."""
    demo_dates = POL["calendar"]["week_12_demo"]["dates"]
    for code in COHORTS:
        for rid, status, week, note in (
            ("TEST2", "RETIRED", None, "Practical Test 2 was dropped on 2 November 2026 because the semester now ends at Week 12. No submission and no mark."),
            ("DEMO", "DATE_TO_BE_CONFIRMED", 12, f"Week 12 short project demo on {demo_dates[code]} (about five minutes per team, questions from the class). Submission window and mark scheme: to be confirmed by the lecturer."),
            ("ML_PROJECT", "DATE_TO_BE_CONFIRMED", 12, "Engineering ML project. Milestones, due date and mark scheme: to be confirmed by the lecturer. The semester ends at Week 12.")):
            hits = [x for x in rows if x["key"] == f"{code}|{rid}"]
            assert len(hits) == 1, (code, rid, len(hits))
            r = hits[0]
            if "original_opens_at" not in r:
                r["original_opens_at"] = r["opens_at"]; r["original_closes_at"] = r["closes_at"]; r["original_week"] = r["week"]
            r["opens_at"] = None; r["closes_at"] = None; r["status"] = status; r["delivery_note"] = note
            if rid == "TEST2": r["retired"] = True
            if week: r["week"] = week


