"""Create the link index and machine-readable QR codes from a deployed URL."""
import argparse,json
from pathlib import Path
from urllib.parse import urlencode,urlsplit
import qrgen
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('url',help='Verified Apps Script deployment URL ending in /exec');p.add_argument('--public-url',help='Verified HTTPS student gateway URL (no query or fragment)');a=p.parse_args()
u=urlsplit(a.url)
if u.scheme!='https' or u.netloc!='script.google.com' or not u.path.startswith('/macros/s/') or not u.path.endswith('/exec') or u.query or u.fragment:p.error('Use the verified canonical Apps Script web app /exec URL.')
public=a.public_url or a.url
if a.public_url:
 v=urlsplit(public)
 if v.scheme!='https' or not v.netloc or v.username or v.password or v.query or v.fragment:p.error('Public URL must be a verified HTTPS gateway address without credentials, query or fragment.')
 public=public.rstrip('/')+'/'
links={};qrdir=ROOT/'qr/test_entry';qrdir.mkdir(parents=True,exist_ok=True)
for course in ['CML3111','CML3112','CML3113']:
 for test in ['TEST1','TEST2']:
  key=course+'|'+test;url=public+'?'+urlencode({'test':key});links[key]=url
  qrgen.png(url,qrdir/(course+'_'+test+'.png'),ec='M',module_px=12,quiet=4)
(ROOT/'data/test_portal_config.json').write_text(json.dumps({'deployment_url':a.url,'public_url':public,'links':links},indent=2)+'\n')
text=['# Test entry links','','Share the course/test entry link, not a ZIP or a blank submission form. The entry page issues each learner’s notebook and CSV during the authorised test window.','','| Course | Test 1 Week 7 | Test 2 Week 14 |','|---|---|---|']
for course in ['CML3111','CML3112','CML3113']:text.append('| '+course+' | [Open Test 1]('+links[course+'|TEST1']+') | [Open Test 2]('+links[course+'|TEST2']+') |')
text+=['','The same links remain usable when test windows are updated. Students finish through the form link generated by their notebook’s Submit test button.','']
(ROOT/'IUEA_Teaching_Plan/test_operations/TEST_ENTRY_LINKS.md').write_text('\n'.join(text))
print('Wrote six links and QR codes.')
