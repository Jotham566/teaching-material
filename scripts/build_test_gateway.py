"""Reuse the beginner portal page with a same-origin API instead of Google browser RPC."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
portal=ROOT/'IUEA_Teaching_Plan/test_portal'
page=(portal/'Index.html').read_text()
page=page.replace('<base target="_top">','')
page=page.replace('<?!= JSON.stringify(testKey) ?>','__TEST_KEY_JSON__')
page=page.replace("let objectUrls=[];",'''async function getFiles(success,failure,input){
 try {
  const response=await fetch('/api/files',{method:'POST',headers:{'Content-Type':'application/json'},credentials:'omit',cache:'no-store',body:JSON.stringify(input)});
  const result=await response.json();
  if(!response.ok||!result.ok)throw Error(result.error||'Could not prepare files. Tell your lecturer.');
  success(result.result);
 } catch(error){failure(error);}
}
let objectUrls=[];''')
assert 'google.script.run.withSuccessHandler(' in page
page=page.replace('google.script.run.withSuccessHandler(', 'getFiles(').replace('}).withFailureHandler(', '},').replace('}).requestTestFiles(input);','},input);')
assert 'google.script.run' not in page
(portal/'gateway/page.mjs').write_text('// Generated by scripts/build_test_gateway.py.\nexport default '+json.dumps(page,ensure_ascii=False)+';\n')
print('Built student page with same-origin requests only.')
