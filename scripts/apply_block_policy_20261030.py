"""Apply the block assessment arrangement (data/assessment_blocks_20261030.json).

  * moves the A7 to A11 closing times in data/assessments.json to the block deadlines;
  * writes grader/apply_block_windows_20261030.gs (run applyBlockWindows() once, it calls setSubmissionWindow);
  * writes grader/block_quiz_sittings_20261030.gs (open_Block1_CML31xx / open_Block2_CML31xx open the three forms together);
  * rewrites the A7 to A11 rows of Assignment_Submission_Links.md.
Usage: python3 scripts/apply_block_policy_20261030.py   (idempotent)"""
import json, re
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]; BASE = ROOT / "IUEA_Teaching_Plan"
POL = json.loads((ROOT / "data" / "assessment_blocks_20261030.json").read_text())
COHORTS = ("CML3111", "CML3112", "CML3113")


def stamp(s): return datetime.fromisoformat(s)


def main():
    path = ROOT / "data" / "assessments.json"; rows = json.loads(path.read_text()); calls = []; closes = {}
    for b in POL["blocks"]:
        for p in b["assignment_parts"]:
            for code in COHORTS:
                r = next(x for x in rows if x["key"] == f"{code}|{p['id']}")
                new_close = b["assignment_closes"][code]
                r["closes_at"] = new_close; r["block"] = b["id"]; r["block_part"] = p["part"]
                r["delivery_note"] = f"{b['label']} assignment, part {p['part']} of {len(b['assignment_parts'])}. All parts of the block close together."
                closes[(code, p["label"])] = (r["opens_at"], new_close)
                calls.append((r["key"], r["opens_at"], new_close))
    path.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n")
    gs = ["/** Generated by scripts/apply_block_policy_20261030.py. Run applyBlockWindows() once from the submission script project.",
          " *  It moves the A7 to A11 closing times to the block deadlines. Opening times are unchanged. */", "function applyBlockWindows() {", "  var calls = " + json.dumps(calls, indent=2) + ";",
          "  calls.forEach(function (c) { setSubmissionWindow(c[0], c[1], c[2]); Logger.log('set ' + c[0] + ' closes ' + c[2]); });", "}", ""]
    (BASE / "grader" / "apply_block_windows_20261030.gs").write_text("\n".join(gs))
    qs = ["/** Generated by scripts/apply_block_policy_20261030.py. Paste into the quiz script project next to create_quiz_forms.gs.",
          " *  A block quiz is the three weekly forms opened together. Each form stays open for WINDOW_HOURS and the three marks add up to 15. */"]
    for b in POL["blocks"]:
        n = b["id"][1:]
        for code in COHORTS:
            body = " ".join(f"openQuizFor({w}, '{code}');" for w in b["weeks"])
            qs += [f"function open_Block{n}_{code}() {{ {body} }}"]
        for code in COHORTS:
            body = " ".join(f"closeQuiz({w}, '{code}');" for w in b["weeks"])
            qs += [f"function close_Block{n}_{code}() {{ {body} }}"]
    (BASE / "grader" / "block_quiz_sittings_20261030.gs").write_text("\n".join(qs) + "\n")
    # links table rows
    md = BASE / "Assignment_Submission_Links.md"; text = md.read_text(); count = 0
    for (code, label), (opens, close) in closes.items():
        pat = re.compile(rf"(?m)^(\| {label}: [^|]*\| )([^|]*)( \| )([^|]*)( \| \[Submit\]\([^)]*\) \|)$")
        sec = text.index(f"## {code}"); nxt = text.find("\n## ", sec + 1); nxt = len(text) if nxt < 0 else nxt
        seg = text[sec:nxt]; new, n = pat.subn(lambda m: m.group(1) + m.group(2) + m.group(3) + close + m.group(5), seg, count=1)
        count += n; text = text[:sec] + new + text[nxt:]
    note = "\n**From Week 8 the weekly assignment and quiz become block assessments.** A7, A8 and A9 form Block 1 and close together; A10 and A11 form Block 2 and close together. The closing times in the tables below are the block deadlines. The arrangement is in [Block_Assessment_Arrangement_2026-10-30.md](Block_Assessment_Arrangement_2026-10-30.md).\n"
    if "From Week 8 the weekly assignment" not in text: text = text.replace("\n## CML3111", note + "\n## CML3111", 1)
    md.write_text(text)
    print(f"registry rows updated: {len(calls)}; link-table rows rewritten: {count}")


if __name__ == "__main__":
    main()
